import { ApplicationConfig, provideBrowserGlobalErrorListeners } from '@angular/core';
import {
  provideRouter,
  withComponentInputBinding,
  withViewTransitions,
  withInMemoryScrolling,
} from '@angular/router';
import { provideHttpClient, withFetch, withInterceptors } from '@angular/common/http';
import { provideClientHydration, withEventReplay } from '@angular/platform-browser';

import { routes } from './app.routes';
// import { authInterceptor } from './core/auth-interceptor';

/**
 * Root application providers for a modern Angular v21/v22 app.
 *
 * NOTE: Angular v21+ is ZONELESS BY DEFAULT — you do NOT add
 * `provideZonelessChangeDetection()`; it is automatic. Only add
 * `provideZoneChangeDetection()` if you must keep Zone.js (not recommended).
 */
export const appConfig: ApplicationConfig = {
  providers: [
    // Catches errors Angular doesn't otherwise handle. Generated by the CLI (v20+).
    provideBrowserGlobalErrorListeners(),

    provideRouter(
      routes,
      withComponentInputBinding(), // route params/data/query bind to component input()s
      withViewTransitions(), // animated route transitions (View Transitions API)
      withInMemoryScrolling({
        scrollPositionRestoration: 'enabled',
        anchorScrolling: 'enabled',
      }),
    ),

    provideHttpClient(
      withFetch(), // use the fetch backend (recommended; required for some SSR setups)
      withInterceptors([
        /* authInterceptor */
      ]), // functional interceptors only
    ),

    // SSR / hydration. Keep if you scaffolded with `ng new --ssr`.
    // `withEventReplay()` replays user events that happened before hydration.
    // For large pages, swap to `withIncrementalHydration()` (it also enables event replay)
    // and use `@defer (hydrate ...)` blocks in templates.
    provideClientHydration(withEventReplay()),
  ],
};
